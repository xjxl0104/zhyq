def build():
    cats = []
    for i, (code, name, sec) in enumerate(TOPS):
        cats.append(dict(code=code, parent=None, name=name, sort=(i + 1) * 10, secret=sec))
    for i, (code, name, sec) in enumerate(SUBS):
        cats.append(dict(code=code, parent=code.split(".")[0], name=name, sort=i + 1, secret=sec))
    rules = []
    for cat, items in CAT_RULES.items():
        for kw, w in items:
            rules.append(dict(keyword=kw, scope=1, category=cat, docType=None, secret=None, weight=w))
    for cat, items in CONTENT_ONLY.items():
        for kw, w in items:
            rules.append(dict(keyword=kw, scope=2, category=cat, docType=None, secret=None, weight=w))
    for kw, t, w in DOC_RULES:
        rules.append(dict(keyword=kw, scope=1, category=None, docType=t, secret=None, weight=w))
    for kw, s in SECRET_RULES:
        rules.append(dict(keyword=kw, scope=1, category=None, docType=None, secret=s, weight=5))
    return cats, rules


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, int):
        return str(v)
    return "'" + str(v).replace("\\", "\\\\").replace("'", "''") + "'"


